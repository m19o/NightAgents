#!/usr/bin/env python3
"""Simulated third-party threat-intel feed for the NightAgents live demo.

LAB SIMULATION - clearly labeled. Serves VirusTotal/Shodan/CT-log/passive-DNS/
abuse-style JSON observations about the demo redirector assets over HTTPS
(self-signed cert generated by the container entrypoint). In production the
same NightAgents config points at the real providers; nothing else changes.

Endpoints: /virustotal /shodan /ctlog /passive-dns /abuse /clean
"""

import json
import ssl
from datetime import UTC, datetime
from http.server import BaseHTTPRequestHandler, HTTPServer

BURNED_DOMAIN = "burned.redirector.demo"
ROUTE = "route-demo-live"

SOURCES = {
    "/virustotal": {
        "source": "virustotal",
        "observations": [
            {
                "indicator": BURNED_DOMAIN,
                "type": "domain_flag",
                "detail": "12/90 engines flag domain as malicious (C2)",
                "verdict": "malicious",
                "engines": 12,
            }
        ],
    },
    "/shodan": {
        "source": "shodan",
        "observations": [
            {
                "indicator": BURNED_DOMAIN,
                "type": "host_profile",
                "detail": "open ports 80,8080; nginx; TLS cert fingerprint published",
                "ports": [80, 8080],
            }
        ],
    },
    "/ctlog": {
        "source": "certificate_transparency",
        "observations": [
            {
                "indicator": BURNED_DOMAIN,
                "type": "ct_log_entry",
                "detail": "new certificate observed in public CT logs",
                "log": "ct.example/argon2026",
            }
        ],
    },
    "/passive-dns": {
        "source": "passive_dns",
        "observations": [
            {
                "indicator": ROUTE,
                "type": "dns_history",
                "detail": "route recently repointed; short TTL pattern",
                "records": [{"name": BURNED_DOMAIN, "type": "A", "ttl": 30}],
            }
        ],
    },
    "/abuse": {
        "source": "abuse_desk",
        "observations": [
            {
                "indicator": BURNED_DOMAIN,
                "type": "abuse_report",
                "detail": "hosting provider received a C2 abuse complaint",
                "ticket": "ABUSE-2026-0712",
            }
        ],
    },
    "/clean": {"source": "clean", "observations": []},
}


class Handler(BaseHTTPRequestHandler):
    def do_GET(self) -> None:  # noqa: N802 - stdlib naming
        payload = SOURCES.get(self.path.split("?", 1)[0])
        if payload is None:
            self.send_response(404)
            self.end_headers()
            return
        body = json.dumps(
            {**payload, "generated_at": datetime.now(UTC).isoformat(), "lab_simulation": True}
        ).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *args) -> None:
        pass


def main() -> None:
    server = HTTPServer(("0.0.0.0", 8443), Handler)
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain("/certs/cert.pem", "/certs/key.pem")
    server.socket = context.wrap_socket(server.socket, server_side=True)
    print("third-party intel feed (lab simulation) on :8443", flush=True)
    server.serve_forever()


if __name__ == "__main__":
    main()
